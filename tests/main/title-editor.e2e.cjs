'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { pathToFileURL, fileURLToPath } = require('node:url')
const { execFileSync } = require('node:child_process')
const { buildApp, launchApp, ROOT } = require('../zernio/support/electron-app.cjs')

test('title editor previews, exports and reopens without changing the base or old clips', { timeout: 120000 }, async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bridgeclip-title-e2e-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const userDataDir = path.join(root, 'user-data')
  const run = path.join(userDataDir, 'BridgeClip', 'title-test')
  fs.mkdirSync(run, { recursive: true })
  const base = path.join(run, 'clip_00.base.mp4')
  const original = path.join(run, 'clip_00.mp4')
  execFileSync('ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'color=c=blue:s=360x640:r=30:d=3', '-c:v', 'libx264', base])
  fs.copyFileSync(base, original)
  const before = fs.readFileSync(base)
  const options = { enabled: true, mode: 'intro', start: 0, end: 3, size: 42, color: '#000000', background: '#ffffff', opacity: .95, position: 'auto', y: 6, fade: true, style: 'card' }
  const clip = { clip_index: 0, s3_url: pathToFileURL(original).href, duration_ms: 3000, start_time_ms: 0, end_time_ms: 3000, virality_score: .8, layout_type: 'fit', summary: 'Pierwszy tytuł', tags: [], render_fallback: null, title_base_url: pathToFileURL(base).href, title_edit: { text: 'Pierwszy tytuł', options } }
  const output = { job_id: 'title-test', source_video_url: '', source_video_title: 'Test edycji', source_video_duration_seconds: 3, total_clips: 1, clips: [clip], transcript_url: null, plan_url: null, processing_time_seconds: 1, metrics: null }
  fs.writeFileSync(path.join(run, 'job_output.json'), JSON.stringify(output))
  const appDir = buildApp(path.join(root, 'app'))
  fs.symlinkSync(path.join(ROOT, 'engine'), path.join(appDir, 'engine'), 'dir')
  fs.symlinkSync(path.join(ROOT, 'bridge'), path.join(appDir, 'bridge'), 'dir')
  const session = await launchApp({ appDir, userDataDir })
  t.after(() => session.close())
  const page = session.page
  page.on('pageerror', error => console.error('PAGE ERROR:', error.message))
  await page.getByLabel('Link do filmu', { exact: true }).fill('https://youtube.com/watch?v=test')
  await page.getByRole('button', { name: 'Użyj linku', exact: true }).click()
  await page.getByRole('navigation', { name: 'Kroki tworzenia klipów' }).getByRole('button', { name: /Napisy/ }).click()
  const presets = page.getByRole('radiogroup', { name: 'Styl tytułu', exact: true })
  assert.equal(await presets.getByRole('radio').count(), 10)
  await presets.getByRole('radio', { name: 'Fiolet', exact: true }).click()
  assert.equal(await presets.getByRole('radio', { name: 'Fiolet', exact: true }).getAttribute('aria-checked'), 'true')
  assert.equal(await page.getByLabel('Czas wyświetlania', { exact: true }).count(), 0)
  await page.screenshot({ path: '/tmp/bridgeclip-polish-presets.png', fullPage: true })
  await page.getByRole('button', { name: "Biblioteka", exact: true }).click()
  await page.getByText('Test edycji', { exact: true }).click()
  await page.getByRole('button', { name: 'Edytuj tytuł', exact: true }).click()
  await page.getByLabel('Tekst na filmie', { exact: true }).fill('Żółć i polskie litery')
  await page.getByLabel('Nazwa klipu w bibliotece', { exact: true }).fill('Nazwa niezależna od tytułu')
  const images = new Set()
  for (const name of ['Papier', 'Noc', 'Alarm', 'Marker', 'Mięta', 'Fiolet', 'Minimal', 'Kino', 'Komiks', 'Magazyn']) {
    const before = await page.getByRole('dialog').locator('img').getAttribute('src')
    await page.getByRole('radio', { name, exact: true }).click()
    await page.waitForFunction(previous => {
      const img = document.querySelector('[role="dialog"] img')
      return img && img.getAttribute('src') !== previous
    }, before)
    images.add(await page.getByRole('dialog').locator('img').getAttribute('src'))
  }
  assert.equal(images.size, 10, 'every preset creates a distinct image with the export renderer')
  await page.getByLabel('Czas wyświetlania', { exact: true }).selectOption('range')
  await page.getByLabel('Od (sekundy)', { exact: true }).fill('0.5')
  await page.getByLabel('Do (sekundy)', { exact: true }).fill('2')
  await page.getByRole('radio', { name: 'Komiks', exact: true }).click()
  assert.equal(await page.getByLabel('Do (sekundy)', { exact: true }).inputValue(), '2')
  await page.getByRole('button', { name: 'Pokaż moment z tytułem' }).click()
  const exportButton = page.getByRole('button', { name: 'Eksportuj klip', exact: true })
  await exportButton.click({ timeout: 30000 })
  await page.getByRole('dialog').waitFor({ state: 'hidden', timeout: 30000 })
  await page.getByRole('heading', { name: 'Nazwa niezależna od tytułu' }).waitFor()
  const saved = JSON.parse(fs.readFileSync(path.join(run, 'job_output.json')))
  assert.equal(saved.clips[0].title_edit.text, 'Żółć i polskie litery')
  assert.equal(saved.clips[0].title_edit.options.end, 2)
  assert.equal(saved.clips[0].title_edit.options.uppercase, true)
  assert.equal(saved.clips[0].title_edit.options.color, '#ffe234')
  assert.notEqual(saved.clips[0].s3_url, clip.s3_url)
  assert.ok(fs.statSync(fileURLToPath(saved.clips[0].s3_url)).size > 0)
  assert.deepEqual(fs.readFileSync(base), before)
  assert.deepEqual(fs.readFileSync(original), before)
  await page.getByRole('button', { name: 'Edytuj tytuł', exact: true }).click()
  assert.equal(await page.getByLabel('Tekst na filmie', { exact: true }).inputValue(), 'Żółć i polskie litery')
  await page.getByRole('switch', { name: 'Wyświetlaj tytuł', exact: true }).click()
  await exportButton.click({ timeout: 30000 })
  await page.getByRole('dialog').waitFor({ state: 'hidden', timeout: 30000 })
  const disabled = JSON.parse(fs.readFileSync(path.join(run, 'job_output.json')))
  assert.deepEqual(fs.readFileSync(fileURLToPath(disabled.clips[0].s3_url)), before)
  // Invalid IPC input cannot write a file or change metadata.
  const metadataBefore = fs.readFileSync(path.join(run, 'job_output.json'), 'utf8')
  const rejected = await page.evaluate(async ({ run, options }) => {
    try { await window.bridgeclip.clips.exportTitle(run, 0, { name: 'x', text: 'x', options: { ...options, end: -1 } }); return false } catch { return true }
  }, { run, options })
  assert.equal(rejected, true)
  assert.equal(fs.readFileSync(path.join(run, 'job_output.json'), 'utf8'), metadataBefore)
  await page.screenshot({ path: '/tmp/bridgeclip-title-library.png' })
})
